'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright'),{randomUUID}=require('node:crypto');
const {startFixture}=require('./test-support/as-fixture.cjs');

test('real AS intake wizard validates, preserves drafts, and saves on-site work without a deadline',async t=>{
 const fixture=await startFixture();let browser;
 t.after(async()=>{await browser?.close();await fixture.close();});
 browser=await chromium.launch({headless:true,timeout:15000,...(process.platform==='win32'?{channel:'msedge'}:{})});
 const context=await browser.newContext({viewport:{width:1440,height:900}}),page=await context.newPage(),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/*',route=>route.request().url().startsWith(fixture.url)?route.continue():route.abort());
 const headers=()=>({'X-Requested-With':'process-server','Idempotency-Key':randomUUID()});
 assert.equal((await context.request.post(fixture.url+'/api/login',{headers:headers(),data:{id:'admin',password:'Fixture-passphrase-2026!'}})).status(),200);
 await page.goto(fixture.url+'/dashboard.html#as-list');await page.waitForFunction(()=>currentUser?.id==='admin');
 await page.evaluate(()=>openUserModal());
 const userModalSize=await page.locator('#userModal').boundingBox();
 await page.evaluate(()=>closeUserModal(true));
 await page.getByRole('button',{name:'신규 접수',exact:true}).click();
 await page.locator('#asModal>.modal-box').evaluate(el=>Promise.all(el.getAnimations().map(animation=>animation.finished)));
 const asModalSize=await page.locator('#asModal>.modal-box').boundingBox();
 assert.equal(asModalSize.width,userModalSize.width,'AS and new-user modals use the same width');
 assert.equal(asModalSize.height,userModalSize.height,'AS and new-user modals use the same height');
 assert.equal(await page.locator('#asIntakeSteps').isVisible(),true,JSON.stringify(errors));
 assert.equal(await page.locator('#asIntakeSteps [aria-current=step]').textContent(),'1자재 · 위치');
 assert.equal(await page.locator('#asCategoryChoices input:not([hidden])').count(),2);
 const shots=path.join(__dirname,'.artifacts','as-intake-live');fs.mkdirSync(shots,{recursive:true});
 await page.screenshot({path:path.join(shots,'step-1.png')});
 await page.getByRole('radio',{name:'사외',exact:true}).check();
 await page.locator('#asIntakeNext').click();
 assert.equal(await page.locator('#asShip').getAttribute('aria-invalid'),'true');
 await page.locator('#asShip').fill('LIVE-FIXTURE');await page.locator('#asBlock').fill('B-101');
 await page.locator('#asElement').fill('E-01');
 await page.locator('#asIntakeNext').click();
 await page.locator('#asIntakeNext').click();
 assert.equal(await page.locator('#asReasonSelect').getAttribute('aria-invalid'),'true');
 await page.locator('#asReasonSelect').selectOption('기타');await page.locator('#asReason').fill('실제 접수 연결 검증');
 await page.locator('#asActionSelect').selectOption('현장 시수');
 assert.match(await page.locator('#asDeliveryAgreedDateHint').textContent(),/입력하지 않아도/);
 await page.screenshot({path:path.join(shots,'step-2.png')});
 await page.locator('#asIntakePrevious').click();
 assert.equal(await page.locator('#asShip').inputValue(),'LIVE-FIXTURE');
 assert.equal(await page.getByRole('radio',{name:'사외',exact:true}).isChecked(),true);
 await page.locator('#asIntakeNext').click();await page.locator('#asIntakeNext').click();
 assert.equal(await page.locator('#asAmount').isVisible(),true);
 assert.equal(await page.locator('#asFiles').count(),1);
 assert.equal(await page.locator('#asModal').getByText('앞서 입력한 내용',{exact:true}).count(),0);
 await page.screenshot({path:path.join(shots,'step-3.png')});
 await page.locator('#asFiles').setInputFiles({name:'fixture.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n%%EOF')});
 await page.locator('#asIntakeNext').click();await page.locator('#asModal').waitFor({state:'hidden'});
 let item=fixture.read('as.json').list[0];
 assert.equal(item.category,'사외');assert.equal(item.ship,'LIVE-FIXTURE');assert.equal(item.element,'E-01');
 assert.equal(item.action,'현장 시수');assert.equal(item.deliveryAgreedDate,'');assert.equal(item.files.length,1);
 assert.equal(item.reason,'실제 접수 연결 검증');
 // On-site work must also remain actionable after the actual receipt has been saved.
 await page.evaluate(async()=>{await loadAsList();openAsWorkflow(_asFullList[0]);});
 assert.equal(await page.locator('#asJobForm button[type=submit]').isEnabled(),true);
 await page.locator('#asJobForm button[type=submit]').click();await page.locator('#asJobDialog').waitFor({state:'hidden'});
 item=fixture.read('as.json').list[0];assert.equal(item.status,'제작 요청');assert.equal(item.deliveryAgreedDate,'');
 await page.evaluate(async()=>{await loadAsList();openAsModal(_asFullList[0]);});
 await page.locator('#asIntakeNext').click();await page.locator('#asRemark').fill('수정값 보존');
 await page.locator('#asIntakeNext').click();await page.locator('#asIntakeNext').click();
 await page.locator('#asModal').waitFor({state:'hidden'});
 assert.equal(fixture.read('as.json').list[0].remark,'수정값 보존');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>openAsModal());
 await page.screenshot({path:path.join(shots,'mobile.png')});
 const bounds=await page.locator('#asModal>.modal-box').boundingBox();
 assert(bounds.x>=0&&bounds.x+bounds.width<=390&&bounds.y>=0&&bounds.y+bounds.height<=844);
 await page.evaluate(()=>{closeAsModal();openAsModal({..._asFullList[0],category:'기타'});});
 assert.equal(await page.getByRole('radio',{name:'기타',exact:true}).isChecked(),true);
 await page.evaluate(()=>{closeAsModal();openAsModal();});
 assert.equal(await page.getByRole('radio',{name:'기타',exact:true}).isVisible(),false);
 assert.deepEqual(errors,[]);
});
