'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const {startFixture}=require('./test-support/as-fixture.cjs');

test('AS intake prototypes preserve the selected flow without writing business data',async t=>{
  const fixture=await startFixture();let browser;
  t.after(async()=>{await browser?.close();await fixture.close();});
  browser=await chromium.launch({headless:true,timeout:15000,...(process.platform==='win32'?{channel:'msedge'}:{})});
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const page=await context.newPage(),errors=[],writes=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(!['GET','HEAD'].includes(request.method()))writes.push(request.url());});
  await page.route('**/*',route=>route.request().url().startsWith(fixture.url)?route.continue():route.abort());
  for(let option=1;option<=5;option++){
    await page.goto(fixture.url+'/cover-assets/as-intake-option-'+option+'.html');
    await page.getByRole('dialog').waitFor();
    assert.equal(await page.getByRole('navigation',{name:'AS 접수 시안 선택'}).getByRole('link').count(),5);
    assert.equal(await page.locator('.variant-nav [aria-current=page]').textContent(),option+'. '+['기본 3단계','집중형 4단계','좌측 단계형','넓은 2단계','우측 패널형'][option-1]);
  }
  await page.goto(fixture.url+'/cover-assets/as-intake-preview.html?option=1.5');
  assert.equal(await page.locator('.variant-nav [aria-current=page]').textContent(),'1. 기본 3단계');
  await page.goto(fixture.url+'/cover-assets/as-intake-option-1.html');
  assert.equal(await page.getByRole('radio').count(),2);
  await page.getByRole('radio',{name:'사외',exact:true}).check();
  assert.equal(await page.getByRole('heading',{name:'정보',exact:true}).isVisible(),true);
  assert.equal(await page.getByLabel('엘레멘탈').isVisible(),true);
  await page.locator('[data-next]').click();
  assert.equal(await page.locator('#preview-ship').getAttribute('aria-invalid'),'true');
  await page.locator('#preview-ship').fill('<img src=x onerror=alert(1)>');
  await page.locator('#preview-block').fill('B-101');
  await page.locator('[data-next]').click();
  await page.locator('[data-next]').click();
  assert.equal(await page.locator('#preview-reason').getAttribute('aria-invalid'),'true');
  await page.locator('#preview-reason').selectOption('기타');
  await page.locator('[data-next]').click();
  assert.equal(await page.locator('#preview-reasonOther').getAttribute('aria-invalid'),'true');
  await page.locator('#preview-reasonOther').fill('치수 확인 요청');
  await page.locator('#preview-action').selectOption('현장 시수');
  assert.match(await page.locator('[data-wrapper=delivery] > small').textContent(),/입력하지 않아도 됩니다/);
  assert.equal(await page.locator('#preview-delivery').inputValue(),'');
  await page.locator('[data-previous]').click();
  assert.equal(await page.locator('#preview-ship').inputValue(),'<img src=x onerror=alert(1)>');
  assert.equal(await page.getByRole('radio',{name:'사외',exact:true}).isChecked(),true);
  assert.equal(await page.locator('.intake-dialog img').count(),0);
  await page.locator('[data-next]').click();
  await page.locator('[data-next]').click();
  assert.equal(await page.locator('#stepTitle').textContent(),'금액과 첨부파일을 확인하세요.');
  assert.equal(await page.getByText('앞서 입력한 내용',{exact:true}).count(),0);
  assert.equal(await page.locator('.review,.organized-review').count(),0);
  await page.locator('#preview-amount').fill('금액 오류');
  await page.locator('[data-next]').click();
  assert.equal(await page.locator('#preview-amount').getAttribute('aria-invalid'),'true');
  await page.locator('#preview-amount').fill('150000');
  await page.locator('#preview-files').setInputFiles({name:'도면.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n%%EOF')});
  assert.equal(await page.locator('.file-list li').count(),1);
  assert.equal(await page.locator('#preview-amount').inputValue(),'150000');
  await page.locator('[data-next]').click();
  assert.equal(await page.getByRole('heading',{name:'접수 흐름을 모두 확인했어요.'}).isVisible(),true);
  assert.deepEqual(fixture.read('as.json').list,[]);
  assert.deepEqual(writes,[]);
  assert.deepEqual(errors,[]);
  await page.setViewportSize({width:390,height:844});
  await page.goto(fixture.url+'/cover-assets/as-intake-option-1.html');
  await page.getByRole('dialog').waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  const box=await page.getByRole('dialog').boundingBox();
  assert(box.x>=0&&box.x+box.width<=390&&box.y>=0&&box.y+box.height<=844);
});
