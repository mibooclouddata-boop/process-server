'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const {chromium}=require('playwright'),{startFixture}=require('./test-support/as-fixture.cjs');
const HOUR=60*60*1000;
test('real input extends idle time; timeout revokes the cookie and a fresh login works inside the transition frame',async t=>{
  const fixture=await startFixture();let browser;
  t.after(async()=>{await browser?.close();await fixture.close();});
  browser=await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'msedge'}:{})});
  const context=await browser.newContext(),page=await context.newPage();
  await page.route('**/*',route=>route.request().url().startsWith(fixture.url)?route.continue():route.abort());
  const login=await context.request.post(fixture.url+'/api/login',{headers:{'X-Requested-With':'process-server'},data:{id:'admin',password:'Fixture-passphrase-2026!'}});
  assert.equal(login.status(),200);
  await page.clock.install({time:new Date('2026-11-01T00:00:00Z')});
  await page.goto(fixture.url+'/dashboard.html');await page.locator('#asStatsContent').waitFor({state:'visible'});
  await page.clock.fastForward(3*HOUR);await page.mouse.move(100,100);await page.clock.fastForward(HOUR);
  assert.match(page.url(),/dashboard.html$/);assert.equal((await context.request.get(fixture.url+'/api/me')).status(),200);
  await page.clock.fastForward(3*HOUR);await page.locator('#sessionExpiredDialog').waitFor({state:'visible'});
  assert.equal((await context.request.get(fixture.url+'/api/me')).status(),401,'idle timeout invalidates the server session');
  assert.match(page.url(),/dashboard.html$/);
  assert.equal(await page.locator('#sessionExpiredDialog').evaluate(el=>{const r=el.getBoundingClientRect();return Math.abs(r.left+r.width/2-innerWidth/2)<1&&Math.abs(r.top+r.height/2-innerHeight/2)<1;}),true,'popup is centered despite global CSS resets');
  assert.equal(await page.locator('#sessionExpiredDialog button').evaluate(el=>el===document.activeElement),true);
  await page.locator('#sessionExpiredDialog button').click();await page.waitForURL('**/login.html');
  await page.clock.resume();
  await page.locator('#identifier').fill('admin');await page.locator('#password').fill('Fixture-passphrase-2026!');await page.locator('#submitBtn').click();
  await page.waitForURL('**/dashboard.html');await page.frameLocator('#loginTransitionFrame').locator('#asStatsContent').waitFor({state:'visible'});
  assert.equal((await context.request.get(fixture.url+'/api/me')).status(),200,'new login resets the expired activity timestamp');
  // Simulate waking after four hours without running throttled background timers.
  await page.clock.setFixedTime(new Date(Date.parse('2026-11-01T00:00:00Z')+12*HOUR));
  const frame=page.frames().find(frame=>frame.parentFrame()&&frame.url().endsWith('/dashboard.html'));
  await frame.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')));
  await page.locator('#sessionExpiredDialog').waitFor({state:'visible'});
  assert.equal((await context.request.get(fixture.url+'/api/me')).status(),401);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('#sessionExpiredDialog').evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth;}),true);
  await page.locator('#sessionExpiredDialog button').press('Enter');
  await page.waitForURL('**/login.html');assert.equal(await page.locator('#loginTransitionFrame').count(),0);
  assert.equal((await context.request.get(fixture.url+'/api/me')).status(),401);
});
test('entering an already idle dashboard waits for popup confirmation',async t=>{
  const fixture=await startFixture();let browser;
  t.after(async()=>{await browser?.close();await fixture.close();});
  browser=await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'msedge'}:{})});
  const context=await browser.newContext(),page=await context.newPage();
  await context.request.post(fixture.url+'/api/login',{headers:{'X-Requested-With':'process-server'},data:{id:'admin',password:'Fixture-passphrase-2026!'}});
  await page.addInitScript(()=>localStorage.setItem('lastUserActivityAt',String(Date.now()-4*60*60*1000-1)));
  await page.goto(fixture.url+'/dashboard.html');
  await page.locator('#sessionExpiredDialog').waitFor({state:'visible',timeout:5000});
  assert.match(page.url(),/dashboard.html$/);
  assert.equal((await context.request.get(fixture.url+'/api/me')).status(),401);
  await page.locator('#sessionExpiredDialog button').click();await page.waitForURL('**/login.html');
});
